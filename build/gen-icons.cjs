// Build assets/js/icons.js: only the lucide icons Krishna Tools uses + a tiny createIcons().
const fs = require('fs');
const lucide = require('./node_modules/lucide/dist/umd/lucide.js');
const kebab = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').replace(/([a-zA-Z])([0-9])/g, '$1-$2').toLowerCase();
const all = {};
for (const [k, v] of Object.entries(lucide.icons)) all[kebab(k)] = v;
// lucide also exposes aliases under different PascalCase keys; kebab of those covers old names like "home".
const want = [...new Set(fs.readFileSync('icons-reg.txt', 'utf8').split('\n').concat(fs.readFileSync('icons-code.txt', 'utf8').split('\n')).map(s => s.trim()).filter(Boolean))];
const out = {}, missing = [];
const loose = {}; for (const k of Object.keys(all)) loose[k.replace(/-/g, '')] = all[k];
for (const n of want) { if (!all[n] && loose[n.replace(/-/g, '')]) all[n] = loose[n.replace(/-/g, '')]; if (all[n]) out[n] = all[n].map(([t, a]) => [t, Object.fromEntries(Object.entries(a).filter(([k]) => k !== 'key'))]); else missing.push(n); }
const js = `/*! Krishna Tools icon subset — lucide 1.69.0 (ISC licence, https://lucide.dev). Generated by build/gen-icons. ${Object.keys(out).length} icons. */
(function(){'use strict';
var I=${JSON.stringify(out)};
var FULL='https://unpkg.com/lucide@1.69.0/dist/umd/lucide.min.js',loading=null,full=null;
function el(tag,a){var e=document.createElementNS('http://www.w3.org/2000/svg',tag);for(var k in a)e.setAttribute(k,a[k]);return e;}
function make(name,src){var s=el('svg',{xmlns:'http://www.w3.org/2000/svg',width:24,height:24,viewBox:'0 0 24 24',fill:'none',stroke:'currentColor','stroke-width':2,'stroke-linecap':'round','stroke-linejoin':'round'});
 I[name].forEach(function(n){s.appendChild(el(n[0],n[1]));});
 for(var i=0;i<src.attributes.length;i++){var at=src.attributes[i];if(at.name!=='data-lucide'&&at.name!=='class')s.setAttribute(at.name,at.value);}
 s.setAttribute('class',('lucide lucide-'+name+' '+(src.getAttribute('class')||'')).trim());s.setAttribute('aria-hidden','true');return s;}
function createIcons(){var miss=false;document.querySelectorAll('i[data-lucide]').forEach(function(n){var name=n.getAttribute('data-lucide');if(I[name])n.replaceWith(make(name,n));else miss=true;});
 if(!miss)return;
 // An icon this subset does not know (e.g. a new tool): use the full library, loaded once on demand.
 if(full){full.createIcons({icons:full.icons});return;}
 if(loading)return;
 loading=document.createElement('script');loading.src=FULL;
 loading.onload=function(){if(window.lucide&&window.lucide!==api){full=window.lucide;window.lucide=api;full.createIcons({icons:full.icons});}};
 document.head.appendChild(loading);}
var api={createIcons:createIcons,icons:I};window.lucide=api;
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',createIcons);else createIcons();})();
`;
fs.writeFileSync(process.argv[2], js);
console.log('icons', Object.keys(out).length, 'missing', missing.length ? missing.join(',') : 'none', 'bytes', js.length);
